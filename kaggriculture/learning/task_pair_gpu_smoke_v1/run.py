"""Synthetic paired updates on one explicitly matched GPU.

This candidate must be reviewed and separately registered before any actual
GPU attempt. It never reads a checkpoint or real game data, and does not write
model weights. A supervising Linux session must enforce the outer hard deadline.
"""

import argparse
from contextlib import contextmanager, nullcontext
import json
import os
from pathlib import Path
import re
import sys
import time


GAME_SOURCE = Path(__file__).resolve().parents[2]
STAGES = frozenset(('arguments', 'bootstrap', 'device', 'fixture', 'fit', 'acceptance'))
ERROR_TYPES = frozenset(('ValueError', 'RuntimeError', 'TimeoutError', 'ImportError',
                         'ModuleNotFoundError', 'OSError', 'MemoryError', 'KeyboardInterrupt', 'SystemExit'))
CURRENT_STAGE = 'arguments'
INNER_SECONDS = 100
RECEIPT_SCHEMA = 'task-pair-gpu-smoke-receipt-v1'
TOKEN_PATTERN = re.compile(r'[0-9a-f]{32}\Z')
IMPORT_GUARD_SHA = 'c5ec904b6c7af23ffb4a6ddd31dd8aa47a0e760cc892087f07e038b303c65f3d'


def bind_project_imports():
    """Load a bounded, SHA-fixed guard before any project package import."""
    import hashlib
    import stat
    import types
    path = Path(__file__).resolve().with_name('import_guard.py')
    info = path.lstat()
    limit = 1024 * 1024
    if (not stat.S_ISREG(info.st_mode) or stat.S_ISLNK(info.st_mode)
            or getattr(info, 'st_file_attributes', 0) & 0x400 or info.st_size > limit):
        raise ValueError('Untrusted import guard')
    flags = os.O_RDONLY | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    descriptor = os.open(path, flags)
    try:
        current = os.fstat(descriptor)
        if not stat.S_ISREG(current.st_mode) or current.st_size > limit:
            raise ValueError('Untrusted import guard')
        with os.fdopen(descriptor, 'rb', closefd=False) as stream:
            raw = stream.read(limit + 1)
    finally:
        os.close(descriptor)
    if (len(raw) != current.st_size or len(raw) > limit
            or hashlib.sha256(raw).hexdigest() != IMPORT_GUARD_SHA):
        raise ValueError('Import guard identity differs')
    guard = types.ModuleType('smoke_import_guard')
    guard.__file__ = str(path)
    exec(compile(raw, str(path), 'exec', dont_inherit=True), guard.__dict__)
    root = guard.bind(GAME_SOURCE)
    return guard, root


def stage(name):
    global CURRENT_STAGE
    if name not in STAGES:
        raise ValueError('Invalid smoke stage')
    CURRENT_STAGE = name


def device_name(value):
    """Accept a bounded exact device-kind parameter without echoing its value."""
    if (type(value) is not str or not 1 <= len(value) <= 128 or value != value.strip()
            or any(ord(char) < 32 or ord(char) == 127 for char in value)):
        raise ValueError('Invalid requested device identity')
    return value


def receipt_token(value):
    """Validate an ephemeral private pipe token; never print it publicly."""
    if type(value) is not str or TOKEN_PATTERN.fullmatch(value) is None:
        raise ValueError('Invalid receipt token')
    return value


def success_receipt(result, token):
    """Construct the one canonical receipt after every GPU check succeeds."""
    expected = {'passed': True, 'unique_requested_gpu_matched': True,
                'paired_updates_each': 2, 'aux_nonzero_updates': 2,
                'both_arms_changed': True, 'arms_differ': True,
                'fit_device_and_finite_checks_passed': True}
    if (type(result) is not dict or set(result) != set(expected)
            or any(type(result[key]) is not type(value) or result[key] != value
                   for key, value in expected.items())):
        raise ValueError('Synthetic acceptance receipt differs')
    return {'schema': RECEIPT_SCHEMA, 'token': receipt_token(token), **result}


def select_gpu(jax, expected_name):
    """Require exactly one GPU and exact equality with the caller's device kind."""
    expected_name = device_name(expected_name)
    devices = jax.devices('gpu')
    if (len(devices) != 1 or devices[0].platform != 'gpu'
            or type(devices[0].device_kind) is not str or devices[0].device_kind != expected_name):
        raise ValueError('Requested GPU identity is unavailable or ambiguous')
    return devices[0]


def synthetic_pair(device, check, import_guard=None):
    """Two in-memory updates on an explicit device; caller decides device policy.

    Unit tests pass an explicit CPU. The public execution path first enforces
    ``select_gpu``. Labels and the candidate masks are supervision only, not
    features. Every input below is generated by the existing synthetic fixture.
    """
    import numpy as np
    import jax
    import jax.numpy as jnp
    protected = (nullcontext() if import_guard is None else
                 import_guard[0].protected_search_path(import_guard[1]))
    with protected:
        from learning.task_pair_data_preflight_v1.test_core import fixture
        from learning.task_pair_training_v1 import fit_core, packing
        from learning.task_pair_training_v1.targets import qualifying_groups

    if import_guard is not None:
        import_guard[0].verify_origins(import_guard[1])

    stage('fixture')
    arrays, _, _ = fixture()
    data = arrays[0]
    eligible = qualifying_groups(data, width=4)
    mean = np.zeros(373, dtype=np.float64)
    scale = np.ones(373, dtype=np.float64)
    weights = np.ones(5, dtype=np.float32)
    # Deterministic toy parameters; never loaded from or saved as a checkpoint.
    params = {
        'w0': (np.sin(np.arange(373 * 4, dtype=np.float32) * np.float32(0.03))
               .reshape(373, 4) * np.float32(0.1)),
        'b0': np.asarray([0.4, 0.3, 0.2, 0.5], dtype=np.float32),
        'w1': np.asarray([[0.2, -0.1], [0.3, 0.2], [-0.1, 0.4], [0.1, 0.3]], dtype=np.float32),
        'b1': np.asarray([0.2, 0.1], dtype=np.float32),
        'w2': np.asarray([[0.5], [-0.3]], dtype=np.float32),
        'b2': np.zeros(1, dtype=np.float32),
    }
    batches = np.asarray([[3, 0, 1, 2], [4, 5, 6, 7]], dtype=np.int64)

    def pack(ids):
        return packing.pack_training_batch(data, ids, mean, scale, weights, eligible)

    check()
    stage('fit')
    result = fit_core.fit_pair(params, batches, pack, device=device, check=check)
    stage('acceptance')
    steps = result['steps']
    step_keys = {'aux_gradient_nonzero', 'control_changed', 'experiment_changed', 'arms_differ'}
    if (type(result['completed_updates']) is not int or result['completed_updates'] != 2
            or type(steps) is not list or len(steps) != 2
            or type(result['aux_nonzero_updates']) is not int or result['aux_nonzero_updates'] != 2
            or result['device_platform'] != device.platform
            or result['control_changed_from_initial'] is not True
            or result['experiment_changed_from_initial'] is not True or result['arms_differ'] is not True
            or not all(type(item) is dict and set(item) == step_keys
                       and all(type(item[key]) is bool for key in step_keys)
                       and item['aux_gradient_nonzero'] and item['control_changed']
                       and item['experiment_changed'] for item in steps)):
        raise ValueError('Synthetic paired-update acceptance failed')
    # fit_pair synchronously checks every loss, gradient, parameter and Optax
    # state leaf on the selected device before and after each actual update.
    with jax.default_device(device):
        for key in ('control_params', 'experiment_params'):
            if type(result[key]) is not dict or set(result[key]) != {'w0', 'b0', 'w1', 'b1', 'w2', 'b2'}:
                raise ValueError('Synthetic parameter set differs')
            for leaf in jax.tree_util.tree_leaves(result[key]):
                if not isinstance(leaf, jax.Array) or leaf.devices() != {device}:
                    raise ValueError('Synthetic parameter device changed')
                leaf.block_until_ready()
                finite = jnp.all(jnp.isfinite(leaf))
                if finite.devices() != {device} or not bool(np.asarray(finite.block_until_ready())):
                    raise ValueError('Synthetic parameter is nonfinite')
    check()
    return {'paired_updates_each': 2, 'aux_nonzero_updates': 2,
            'both_arms_changed': True, 'arms_differ': True,
            'fit_device_and_finite_checks_passed': True}


def required_gpu_smoke(expected_name, import_guard=None):
    """Perform the only public execution path; no CPU fallback is permitted."""
    os.environ['XLA_PYTHON_CLIENT_PREALLOCATE'] = 'false'
    deadline = time.monotonic() + INNER_SECONDS

    def check():
        if time.monotonic() >= deadline:
            raise TimeoutError('Synthetic fit deadline exceeded')

    stage('device')
    import jax
    selected = select_gpu(jax, expected_name)
    check()
    result = synthetic_pair(selected, check, import_guard)
    result.update({'passed': True, 'unique_requested_gpu_matched': True})
    return result


@contextmanager
def quiet_native_output():
    """Suppress incidental library output; restore streams before safe JSON."""
    sys.stdout.flush()
    sys.stderr.flush()
    saved_out, saved_err = os.dup(1), os.dup(2)
    sink = os.open(os.devnull, os.O_WRONLY)
    try:
        os.dup2(sink, 1)
        os.dup2(sink, 2)
        yield
    finally:
        sys.stdout.flush()
        sys.stderr.flush()
        os.dup2(saved_out, 1)
        os.dup2(saved_err, 2)
        os.close(saved_out)
        os.close(saved_err)
        os.close(sink)


class QuietParser(argparse.ArgumentParser):
    def error(self, message):
        raise ValueError('Invalid smoke arguments')


def error_result(exc):
    kind = type(exc).__name__
    return {'passed': False, 'stage': CURRENT_STAGE,
            'error_type': kind if kind in ERROR_TYPES else 'OtherError'}


def cli(argv=None):
    stage('arguments')
    parser = QuietParser(add_help=False)
    parser.add_argument('--expected-device-name', required=True)
    parser.add_argument('--receipt-token', required=True)
    try:
        args = parser.parse_args(argv)
        expected = device_name(args.expected_device_name)
        token = receipt_token(args.receipt_token)
        with quiet_native_output():
            stage('bootstrap')
            binding = bind_project_imports()
            actual = required_gpu_smoke(expected, binding)
            binding[0].verify_origins(binding[1])
            result = success_receipt(actual, token)
    except (Exception, KeyboardInterrupt, SystemExit) as exc:
        result = error_result(exc)
    # The success token is sent only to the supervisor's private in-memory pipe.
    print(json.dumps(result, sort_keys=True, separators=(',', ':')), flush=True)
    return 0 if result['passed'] else 1


if __name__ == '__main__':
    sys.exit(cli())
